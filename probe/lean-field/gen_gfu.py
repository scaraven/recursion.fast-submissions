"""Generate GFU.lean: fully unrolled (allocation-free) naive, comb and 4-bit-window variants."""
L = ["/- GENERATED by logs/phase0-M/scripts/gen_gfu.py: unrolled variants, no loops, no allocation. -/",
     "import GF", "namespace GF", "set_option maxRecDepth 100000", ""]
# naive GF(2^128): 128 steps
L.append("@[inline] def mul128NaiveU (alo ahi blo bhi : UInt64) : U128 :=")
L.append("  let rlo : UInt64 := 0\n  let rhi : UInt64 := 0")
for half, b in (("lo", "blo"), ("hi", "bhi")):
    for i in range(64):
        L.append(f"  let m := (0 : UInt64) - (({b} >>> {i}) &&& 1)")
        L.append("  let rlo := rlo ^^^ (alo &&& m)\n  let rhi := rhi ^^^ (ahi &&& m)")
        if not (half == "hi" and i == 63):
            L.append("  let c := (0 : UInt64) - (ahi >>> 63)")
            L.append("  let ahi := (ahi <<< 1) ||| (alo >>> 63)")
            L.append("  let alo := (alo <<< 1) ^^^ (c &&& 0x87)")
L.append("  ⟨rlo, rhi⟩\n")
# comb clmul64: 64 steps
L.append("@[inline] def clmulCombU (a b : UInt64) : U128 :=")
L.append("  let lo : UInt64 := a &&& ((0 : UInt64) - (b &&& 1))\n  let hi : UInt64 := 0")
for i in range(1, 64):
    L.append(f"  let m := (0 : UInt64) - ((b >>> {i}) &&& 1)")
    L.append(f"  let lo := lo ^^^ ((a <<< {i}) &&& m)")
    L.append(f"  let hi := hi ^^^ ((a >>> {64 - i}) &&& m)")
L.append("  ⟨lo, hi⟩\n")
# 4-bit windows, table in locals, lookup by match
L.append("@[inline] def clmulWinMU (a b : UInt64) : U128 :=")
L.append("  let u2 := a <<< 1\n  let u4 := a <<< 2\n  let u8 := a <<< 3")
L.append("  let t : T16 := ⟨0, a, u2, u2 ^^^ a, u4, u4 ^^^ a, u4 ^^^ u2, u4 ^^^ u2 ^^^ a, u8, u8 ^^^ a,")
L.append("    u8 ^^^ u2, u8 ^^^ u2 ^^^ a, u8 ^^^ u4, u8 ^^^ u4 ^^^ a, u8 ^^^ u4 ^^^ u2, u8 ^^^ u4 ^^^ u2 ^^^ a⟩")
L.append("  let lo := t.sel (b &&& 15)\n  let hi : UInt64 := 0")
for i in range(4, 64, 4):
    L.append(f"  let g := t.sel ((b >>> {i}) &&& 15)")
    L.append(f"  let lo := lo ^^^ (g <<< {i})\n  let hi := hi ^^^ (g >>> {64 - i})")
L.append("  ⟨lo, winRepair a b hi⟩\n")
L.append("@[inline] def mul128NaiveU' (alo ahi blo bhi : UInt64) : U128 := mul128NaiveU alo ahi blo bhi")
L.append("@[inline] def mul128CombU (alo ahi blo bhi : UInt64) : U128 := kara clmulCombU alo ahi blo bhi")
L.append("@[inline] def mul128WinMU (alo ahi blo bhi : UInt64) : U128 := kara clmulWinMU alo ahi blo bhi")
L.append("@[inline] def mul64CombU (a b : UInt64) : UInt64 := let p := clmulCombU a b; red64 p.lo p.hi")
L.append("\nend GF")
print("\n".join(L))
