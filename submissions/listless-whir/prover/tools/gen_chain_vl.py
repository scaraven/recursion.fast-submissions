#!/usr/bin/env python3
"""PORT-12: write src/keccak_vl.rs, relay-echo's (PR #12, Apache-2.0) AVX-512VL chain kernel as one Rust `asm!`
statement per variant. The loop body is `gen_vlasm.gen_body` (vendored, unmodified), with GCC's `%%xmmN` and
`%[k]` rewritten to `%xmmN` and `{k}`; the store of every step's digest lanes (`Y_i`) is added here.

The Rust wrapper and the constant table follow relay-echo's keccak_vlasm.inc (Apache-2.0; see ../../LICENSE).

Usage (from prover/): python3 -I tools/gen_chain_vl.py > src/keccak_vl.rs
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_vlasm  # noqa: E402

ALLOWED = {"vpsllq", "vpsrlq", "vporq", "vpxorq", "vmovdqa64", "vprolq", "vpternlogq", "vpandnq"}
OPND = re.compile(r"^(\$(0x[0-9A-Fa-f]+|[0-9]+)|%xmm([0-9]|[12][0-9]|3[01])|[0-9]+\(\{k\}\))$")


def body_ins():
    """The loop body, in Rust's asm! form, every instruction checked against a whitelist."""
    out = []
    for s in gen_vlasm.gen_body(gen_vlasm.KERNELS["avx512vl"]):
        ins = s.replace("%%", "%").replace("%[k]", "{k}")
        mn, _, ops = ins.partition(" ")
        assert mn in ALLOWED, ins
        assert all(OPND.match(o.strip()) for o in ops.split(",")), ins
        out.append(f'"{ins}",')
    return ["// " + f"{len(out)} instructions per step: gen_vlasm.gen_body (avx512vl)"] + out
RC = [0x0000000000000001, 0x0000000000008082, 0x800000000000808A, 0x8000000080008000,
      0x000000000000808B, 0x0000000080000001, 0x8000000080008081, 0x8000000000008009,
      0x000000000000008A, 0x0000000000000088, 0x0000000080008009, 0x000000008000000A,
      0x000000008000808B, 0x800000000000008B, 0x8000000000008089, 0x8000000000008003,
      0x8000000000008002, 0x8000000000000080, 0x000000000000800A, 0x800000008000000A,
      0x8000000080008081, 0x8000000000008080, 0x0000000080000001, 0x8000000080008008]
CONSTS = RC + [0x43, 0x100, 0x8000000000000000]

HEADER = '''// Generated by tools/gen_chain_vl.py from tools/gen_vlasm.py (relay-echo's generator; do not edit).
//
// Derived from relay-echo (scaraven/recursion.fast-submissions PR #12, submissions/relay-echo), licensed under
// the Apache License, Version 2.0 (http://www.apache.org/licenses/LICENSE-2.0; a copy is in this entry's
// LICENSE). Changes (PORT-12): the loop body of `chain2_avx512vl` translated from GCC extended asm to one Rust
// `asm!` statement (AT&T syntax, same instructions, same registers); a store of each step's digest lanes
// (`Y_i`, lanes 0-3 of the output) into one or two arrays added at the end of every step; the C wrapper
// replaced by the functions below.
//! The chain `d <- Keccak-256(0x43 || d)` with AVX-512F/VL, one lane per xmm register, two independent
//! chains in the two qwords (relay-echo's `avx512vl` kernel). Round 0 skips the lanes that are zero in every
//! chain block, round 23 computes only the four digest lanes. Agrees with `keccak::chain_step` (`kat keccak`).

#[cfg(all(target_arch = "x86_64", target_feature = "avx512f", target_feature = "avx512vl", target_feature = "avx512dq"))]
mod imp {
    #[repr(C, align(16))]
    struct Consts([[u64; 2]; 27]);
    /// The 24 round constants, then `0x43`, `0x01 << 8` and `0x80 << 56` (the chain block's fixed bytes), each
    /// in both qwords.
    static K: Consts = Consts([
%CONSTS%
    ]);

    /// `n ≥ 1` steps of the two chains from `ha`, `hb` (digest lanes); writes step `i`'s lanes to `ya[i]` and,
    /// when `two`, to `yb[i]`. Returns the two ends.
    ///
    /// # Safety
    /// `ya` (and `yb` when `two`) must be valid for `n` writes of `[u64; 4]`.
    #[inline(never)]
    pub unsafe fn walk(ha: [u64; 4], hb: [u64; 4], n: usize, ya: *mut [u64; 4], yb: *mut [u64; 4], two: bool) -> ([u64; 4], [u64; 4]) {
        let mut hv: [[u64; 2]; 4] = std::array::from_fn(|i| [ha[i], hb[i]]);
        if n == 0 {
            return (ha, hb);
        }
        let h = hv.as_mut_ptr();
        if two {
            unsafe { body2(h, n, ya, yb) }
        } else {
            unsafe { body1(h, n, ya) }
        }
        (std::array::from_fn(|i| hv[i][0]), std::array::from_fn(|i| hv[i][1]))
    }

%BODIES%
}

/// Whether this build carries the kernel.
pub const AVAILABLE: bool = cfg!(all(target_arch = "x86_64", target_feature = "avx512f", target_feature = "avx512vl", target_feature = "avx512dq"));

/// `n` chain steps from the digest lanes `h`: `y[i]` = lanes 0-3 of step `i`'s output (`y.len() = n`).
#[cfg(all(target_arch = "x86_64", target_feature = "avx512f", target_feature = "avx512vl", target_feature = "avx512dq"))]
pub fn walk(h: [u64; 4], y: &mut [[u64; 4]]) -> [u64; 4] {
    // SAFETY: `y` holds `y.len()` entries; `yb` is not written when `two` is false.
    unsafe { imp::walk(h, h, y.len(), y.as_mut_ptr(), std::ptr::null_mut(), false).0 }
}

/// Two chains at once (step 1): `ya.len() == yb.len()` steps of each.
#[cfg(all(target_arch = "x86_64", target_feature = "avx512f", target_feature = "avx512vl", target_feature = "avx512dq"))]
pub fn walk2(ha: [u64; 4], hb: [u64; 4], ya: &mut [[u64; 4]], yb: &mut [[u64; 4]]) -> ([u64; 4], [u64; 4]) {
    assert_eq!(ya.len(), yb.len());
    // SAFETY: both slices hold `ya.len()` entries.
    unsafe { imp::walk(ha, hb, ya.len(), ya.as_mut_ptr(), yb.as_mut_ptr(), true) }
}
'''

CLOBBERS = ", ".join(f'out("xmm{i}") _' for i in range(32))


def body(name, two, ins):
    pre = ['"vmovdqu64 0({h}), %xmm26",', '"vmovdqu64 16({h}), %xmm27",',
           '"vmovdqu64 32({h}), %xmm28",', '"vmovdqu64 48({h}), %xmm29",', '"2:",']
    st = [f'"vmovq %xmm{26 + j}, {8 * j}({{ya}})",' for j in range(4)]
    if two:
        st += [f'"vpextrq $1, %xmm{26 + j}, {8 * j}({{yb}})",' for j in range(4)]
    st += ['"addq $32, {ya}",'] + (['"addq $32, {yb}",'] if two else [])
    post = ['"decq {n}",', '"jnz 2b",', '"vmovdqu64 %xmm26, 0({h})",', '"vmovdqu64 %xmm27, 16({h})",',
            '"vmovdqu64 %xmm28, 32({h})",', '"vmovdqu64 %xmm29, 48({h})",']
    lines = pre + ins + st + post
    sig = "h: *mut [u64; 2], n: usize, ya: *mut [u64; 4]" + (", yb: *mut [u64; 4]" if two else "")
    ops = ['h = in(reg) h', 'k = in(reg) K.0.as_ptr()', 'n = inout(reg) n => _', 'ya = inout(reg) ya => _']
    if two:
        ops.append('yb = inout(reg) yb => _')
    out = [f"    #[inline(always)]", f"    unsafe fn {name}({sig}) {{",
           "        // SAFETY (caller): `h` points to 4 x 16 bytes, `ya`/`yb` to `n` entries.",
           "        unsafe {", "            core::arch::asm!("]
    out += ["                " + l for l in lines]
    out += ["                " + o + "," for o in ops]
    out += ["                " + CLOBBERS + ",", "                options(att_syntax, nostack),", "            );",
            "        }", "    }"]
    return "\n".join(out)


def main():
    ins = body_ins()
    consts = "\n".join(f"        [0x{c:016X}, 0x{c:016X}]," for c in CONSTS)
    bodies = body("body1", False, ins) + "\n\n" + body("body2", True, ins)
    print(HEADER.replace("%CONSTS%", consts).replace("%BODIES%", bodies), end="")


if __name__ == "__main__":
    main()
