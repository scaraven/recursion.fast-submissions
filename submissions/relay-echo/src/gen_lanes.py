#!/usr/bin/env python3
"""Generates keccak_lanes.inc: Keccak-f[1600] in the plain form (no lane complementing), 24 rounds
unrolled, one lane per 64-bit variable, for CPUs with BMI1 and BMI2: chi is ANDN + XOR, the rotations are
RORX (non-destructive, so fewer copies), and theta computes D[x] once per column.

It holds the whole permutation, keccak_f_bmi (the tests), and the chain d <- Keccak-256(0x43 || d),
n times, chain_bmi.  Both carry target("bmi,bmi2"), so the file compiles at the baseline x86-64 target
and the callers dispatch on cpuid.  Usage: gen_lanes.py > keccak_lanes.inc
"""
import sys

RC = [0x0000000000000001, 0x0000000000008082, 0x800000000000808A, 0x8000000080008000,
      0x000000000000808B, 0x0000000080000001, 0x8000000080008081, 0x8000000000008009,
      0x000000000000008A, 0x0000000000000088, 0x0000000080008009, 0x000000008000000A,
      0x000000008000808B, 0x800000000000008B, 0x8000000000008089, 0x8000000000008003,
      0x8000000000008002, 0x8000000000000080, 0x000000000000800A, 0x800000008000000A,
      0x8000000080008081, 0x8000000000008080, 0x0000000080000001, 0x8000000080008008]
RHO = [0, 1, 62, 28, 27, 36, 44, 6, 55, 20, 3, 10, 43, 25, 39, 41, 45, 15, 21, 8, 18, 2, 61, 56, 14]


def emit_rounds(w):
    """The 24 rounds on lanes a0..a24; returns the names of the 25 output lanes."""
    cur = ['a%d' % i for i in range(25)]
    for r in range(24):
        p = 'r%d_' % r
        for x in range(5):
            w('        uint64_t %sc%d = ((%s ^ %s) ^ (%s ^ %s)) ^ %s;'
              % (p, x, cur[x], cur[x + 5], cur[x + 10], cur[x + 15], cur[x + 20]))
        for x in range(5):
            w('        uint64_t %sd%d = %sc%d ^ ROL64(%sc%d, 1);' % (p, x, p, (x + 4) % 5, p, (x + 1) % 5))
        b = [None] * 25
        for x in range(5):
            for y in range(5):
                i = x + 5 * y
                j = y + 5 * ((2 * x + 3 * y) % 5)
                src = '%s ^ %sd%d' % (cur[i], p, x)
                w('        uint64_t %sb%d = %s;' % (p, j, ('ROL64(%s, %d)' % (src, RHO[i])) if RHO[i] else src))
                b[j] = '%sb%d' % (p, j)
        nxt = [None] * 25
        for y in range(5):
            for x in range(5):
                i = x + 5 * y
                rc = (' ^ 0x%016Xull' % RC[r]) if i == 0 else ''
                w('        uint64_t %se%d = (%s ^ (~%s & %s))%s;'
                  % (p, i, b[i], b[(x + 1) % 5 + 5 * y], b[(x + 2) % 5 + 5 * y], rc))
                nxt[i] = '%se%d' % (p, i)
        cur = nxt
    return cur


def gen():
    out = []
    w = out.append
    w('/* generated by gen_lanes.py (do not edit): Keccak-f[1600] in the plain form, 24 rounds unrolled, for BMI1/BMI2:')
    w('   keccak_f_bmi (the whole permutation) and chain_bmi. */')
    w('#pragma GCC diagnostic push')
    w('#pragma GCC diagnostic ignored "-Wunused-variable"   /* the chain\'s last round computes lanes it drops */')
    w('#define ROL64(v, n) (((v) << (n)) | ((v) >> (64 - (n))))')
    w('__attribute__((target("bmi,bmi2"))) static void keccak_f_bmi(uint64_t st[25]) {')
    w('    {')
    for i in range(25):
        w('        uint64_t a%d = st[%d];' % (i, i))
    cur = emit_rounds(w)
    for i in range(25):
        w('        st[%d] = %s;' % (i, cur[i]))
    w('    }')
    w('}')
    w('/* n steps of d <- Keccak-256(0x43 || d), the 33-byte message padded in place */')
    w('__attribute__((target("bmi,bmi2"))) static void chain_bmi(uint8_t out[32], const uint8_t in[32], uint64_t n) {')
    w('    uint64_t h0, h1, h2, h3;')
    w('    memcpy(&h0, in, 8); memcpy(&h1, in + 8, 8); memcpy(&h2, in + 16, 8); memcpy(&h3, in + 24, 8);')
    w('    for (uint64_t it = 0; it < n; it++) {')
    # lane k = bytes 8k..8k+7 of (0x43 || d || 0x01 || zeros || 0x80)
    init = ['0x43ull | h0 << 8', 'h0 >> 56 | h1 << 8', 'h1 >> 56 | h2 << 8', 'h2 >> 56 | h3 << 8',
            'h3 >> 56 | 0x100ull'] + ['0'] * 11 + ['0x8000000000000000ull'] + ['0'] * 8
    for i in range(25):
        w('        uint64_t a%d = %s;' % (i, init[i]))
    cur = emit_rounds(w)
    for i in range(4):
        w('        h%d = %s;' % (i, cur[i]))
    w('    }')
    w('    memcpy(out, &h0, 8); memcpy(out + 8, &h1, 8); memcpy(out + 16, &h2, 8); memcpy(out + 24, &h3, 8);')
    w('}')
    w('#undef ROL64')
    w('#pragma GCC diagnostic pop')
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    sys.stdout.write(gen())
