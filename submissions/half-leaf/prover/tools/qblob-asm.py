#!/usr/bin/env python3
"""R8 (PATCHES.md): the circuit `Q`'s compact form as GNU assembly, linked beside the tiers.

  python3 -I tools/qblob-asm.py QBIN OUT.s

QBIN is `lvm6-prover qpack BLOB QBIN`'s output (`r3typed::qbin`, magic `LVM6QC2`). OUT.s defines, in `.rodata`,
`lvm6_qblob` (the bytes, zero-padded to whole 8-byte words, as `.quad` lines of eight words) and `lvm6_qblob_len`
(the byte count), which every tier of an `embedded-q` build references (`r3typed::qbin::embedded`). No `.incbin`:
the runner's build sees only the `.s` files. Deterministic: the same QBIN gives the same bytes.
"""
import sys

def main():
    src, dst = sys.argv[1], sys.argv[2]
    data = open(src, 'rb').read()
    if data[:7] != b'LVM6QC2' or data[7] not in (0, 17):  # R9: byte 7 is the shape tag (0 = P18, 17 = P17)
        raise SystemExit(f"qblob-asm: {src} is not a compact Q (magic {data[:8]!r})")
    n = len(data)
    data += b'\0' * (-n % 8)
    words = [int.from_bytes(data[i:i + 8], 'little') for i in range(0, len(data), 8)]
    out = [
        f"# lvm6 R8: the circuit Q, compact form ({n} bytes, Keccak-256 of the text blob {data[8:40].hex()})",
        "# generated by tools/qblob-asm.py from `lvm6-prover qpack`; read by r3typed::qbin::embedded",
        '\t.section\t.rodata.lvm6_qblob,"a",@progbits',
        "\t.globl\tlvm6_qblob",
        "\t.type\tlvm6_qblob,@object",
        "\t.p2align\t6",
        "lvm6_qblob:",
    ]
    for i in range(0, len(words), 8):
        out.append("\t.quad\t" + ",".join(f"0x{w:x}" for w in words[i:i + 8]))
    out += [
        f"\t.size\tlvm6_qblob, {len(data)}",
        "\t.globl\tlvm6_qblob_len",
        "\t.type\tlvm6_qblob_len,@object",
        "\t.p2align\t3",
        "lvm6_qblob_len:",
        f"\t.quad\t{n}",
        "\t.size\tlvm6_qblob_len, 8",
        '\t.section\t.note.GNU-stack,"",@progbits',
        "",
    ]
    with open(dst, 'w', newline='\n') as f:
        f.write("\n".join(out))

if __name__ == '__main__':
    main()
