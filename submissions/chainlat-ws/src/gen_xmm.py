#!/usr/bin/env python3
"""Generate chain_words_xmm: one Keccak lane per xmm register, with pi applied as a
symbolic register renaming (no data movement), chi writing its outputs directly into
the registers freed by the row's consumed rho-pi sources.

Round structure (FIPS 202, lane index k = x + 5y):
  theta: c_x = xor of column x; a[k] ^= c[x-1] ^ rol(c[x+1], 1)
  rho+pi: out lane k <- rol(in lane l(k), RHO[l(k)]), l(k) = ((x+3y)%5) + 5x for k = x+5y
  chi: out(k) = b(k) ^ (~b(x+1,y) & b(x+2,y))   (row-local)
  iota: lane 0 ^= RC[r]

Live set: 25 state + 5 row temps + 2 saves = 32 xmm registers.
Emits C; each register is a __m128i variable, one uop per statement.
"""
RC = [0x0000000000000001, 0x0000000000008082, 0x800000000000808a, 0x8000000080008000, 0x000000000000808b, 0x0000000080000001, 0x8000000080008081, 0x8000000000008009, 0x000000000000008a, 0x0000000000000088, 0x0000000080008009, 0x000000008000000a, 0x000000008000808b, 0x800000000000008b, 0x8000000000008089, 0x8000000000008003, 0x8000000000008002, 0x8000000000000080, 0x000000000000800a, 0x800000008000000a, 0x8000000080008081, 0x8000000000008080, 0x0000000080000001, 0x8000000080008008]
RHO = [0, 1, 62, 28, 27, 36, 44, 6, 55, 20, 3, 10, 43, 25, 39,
       41, 45, 15, 21, 8, 18, 2, 61, 56, 14]

def src_of(k):
    x, y = k % 5, k // 5
    return ((x + 3 * y) % 5) + 5 * x

SRC = [src_of(k) for k in range(25)]
# sanity: it is a permutation
assert sorted(SRC) == list(range(25))

def gen():
    # perm[lane] = register variable name currently holding that lane
    perm = {k: f"x{k}" for k in range(25)}
    L = []
    A = L.append
    for r in range(24):
        # theta (apply as d's become ready; mapping unchanged)
        for cx in range(5):
            cols = [k for k in range(25) if k % 5 == cx]
            A(f"c{cx} = " + " ^ ".join(f"_mm_xor_si128({perm[k]})" for k in cols))
        # (emitted below properly; placeholder replaced in emit pass)
    return L

def emit():
    out = []
    P = out.append
    P("/* generated by gen_xmm.py -- do not edit */")
    P('__attribute__((target("avx512f,avx512vl,bmi2")))')
    P("static void chain_words_vec(uint64_t w[4], uint64_t n) {")
    P("    while (n--) {")
    P("        __m128i")
    P("            x0 = _mm_set_epi64x(0, 0x43 ^ (w[0] << 8)),")
    P("            x1 = _mm_set_epi64x(0, (w[0] >> 56) ^ (w[1] << 8)),")
    P("            x2 = _mm_set_epi64x(0, (w[1] >> 56) ^ (w[2] << 8)),")
    P("            x3 = _mm_set_epi64x(0, (w[2] >> 56) ^ (w[3] << 8)),")
    P("            x4 = _mm_set_epi64x(0, (w[3] >> 56) ^ 0x0100ull),")
    P("            x16 = _mm_set_epi64x(0, 0x8000000000000000ull),")
    P("            xz = _mm_setzero_si128();")
    P("        __m128i x5 = xz, x6 = xz, x7 = xz, x8 = xz, x9 = xz, x10 = xz, x11 = xz,")
    P("                x12 = xz, x13 = xz, x14 = xz, x15 = xz, x17 = xz, x18 = xz, x19 = xz,")
    P("                x20 = xz, x21 = xz, x22 = xz, x23 = xz, x24 = xz;")
    P("        __m128i c0, c1, c2, c3, c4, t0, t1, t2, t3, t4, sv3, sv4;")
    perm = {k: f"x{k}" for k in range(25)}
    for r in range(24):
        orig = dict(perm)          # where each lane's post-theta value lives this round
        P(f"        /* round {r} */")
        # theta: parities then d-apply as you go
        for cx in range(5):
            cols = [k for k in range(25) if k % 5 == cx]
            terms = [orig[k] for k in cols]
            e = terms[0]
            for t in terms[1:]:
                e = f"_mm_xor_si128({e}, {t})"
            P(f"        c{cx} = {e};")
        for cx in range(5):
            # a[k in col x] ^= c[(x+4)%5] ^ rol(c[(x+1)%5], 1)
            c1 = f"_mm_rol_epi64(c{(cx + 1) % 5}, 1)"
            P(f"        t{cx} = _mm_xor_si128({c1}, c{(cx + 4) % 5});")
            for k in [k for k in range(25) if k % 5 == cx]:
                P(f"        {orig[k]} = _mm_xor_si128({orig[k]}, t{cx});")
        # rho+pi+chi, row by row: row y's sources are SRC[5y..5y+4]
        for y in range(5):
            srcs = [SRC[5 * y + j] for j in range(5)]
            dests = list(range(5 * y, 5 * y + 5))          # output lanes of this row
            freed = {orig[s]: None for s in srcs}          # registers freed as consumed
            # rol the row's sources into t0..t4
            for j, s in enumerate(srcs):
                P(f"        t{j} = _mm_rol_epi64({orig[s]}, {RHO[s]});")
            # the row's outputs go into the freed source registers; chi needs the
            # original t0..t4, so order writes o3, o4 first (they need saves), then o0..o2
            # destination register for output lane 5y+j: freed[srcs[j]]
            # o3 = TL(t3, t4, t0); o4 = TL(t4, t0, t1); o0 = TL(t0,t1,t2);
            # o1 = TL(t1, t2, sv3); o2 = TL(t2, sv3, sv4)
            P(f"        sv3 = t3; sv4 = t4;")
            d = {j: orig[srcs[j]] for j in range(5)}
            P(f"        {d[3]} = _mm_ternarylogic_epi64(sv3, sv4, t0, 0xD2);")
            P(f"        {d[4]} = _mm_ternarylogic_epi64(sv4, t0, t1, 0xD2);")
            P(f"        {d[0]} = _mm_ternarylogic_epi64(t0, t1, t2, 0xD2);")
            P(f"        {d[1]} = _mm_ternarylogic_epi64(t1, t2, sv3, 0xD2);")
            P(f"        {d[2]} = _mm_ternarylogic_epi64(t2, sv3, sv4, 0xD2);")
            # update the mapping: output lane 5y+j now lives in the freed reg of srcs[j]
            for j in range(5):
                perm[dests[j]] = d[j]
        # iota
        P(f"        {perm[0]} = _mm_xor_si128({perm[0]}, _mm_set1_epi64x(0x{RC[r]:016x}ull));")
    # after 24 rounds the mapping is identity again?  pi^24 = identity, so yes; but be
    # safe: extract via the tracked mapping
    P("        uint64_t o[2];")
    for i, lane in enumerate([0, 1, 2, 3]):
        P(f"        _mm_storeu_si128((__m128i *)(void *)o, {perm[lane]}); w[{i}] = o[0];")
    P("    }")
    P("}")
    return "\n".join(out) + "\n"

print(emit())
