/*
 * chainwalk: the recursion.fast prover for the witness-sending certificate.
 *
 * The Lean half is the organiser library's `WitnessSending` (errors 0, qV = 0, fuel 8t):
 * the proof is the witness, so this program walks each fresh Keccak-256 chain once,
 * wraps the previous signed proof and the new leaf, and gets one SIGN of the empty
 * trace per output (the leaf child's trace digest is the same constant, so the same
 * sigma serves both files).
 *
 * Kernels, dispatched at run time and re-checked against the portable one before the
 * `ready` line of every request:
 *   k_vec  AVX-512VL+F+BMI2, one lane per xmm register, pi applied as a symbolic
 *          register renaming (generated by gen_xmm.py)
 *   k_gp   scalar BMI2 straight-line rounds
 *   k_c    portable scalar reference
 * Step 1's two chains run on two threads; the SIGN and file assembly overlap the walk.
 *
 * Interface: harness/PROVER.md.  File format: harness/FORMAT.md.
 */
#define _GNU_SOURCE
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>
#include <fcntl.h>
#include <errno.h>
#include <pthread.h>
#include <sys/socket.h>
