# phb.py CLS OUTDIR : encode an exporter .cls (PHICLS 3) as PHB 1 lowercase-hex Lean data modules (ST-4, STARTUP2 P4).
# Format: varint 0x5048, varint 1; dictionary (varint D, D little-endian 8-byte words); varint L lines, each varint n
# and n tokens: 4k+1 keyword k, 4v number v (< 2^32), 4d+2 dictionary word d. Modules: Lvm6DataPhi<k>.lean (no
# imports, <= 512 KiB of hex each, `Lvm6.Data.phiHex<k>`) and Lvm6DataPhi.lean (`Lvm6.Data.phiHex`, their concatenation).
import sys, os
KW = ["PHICLS", "WB", "CLASSES", "CLASS", "LOOPS", "LOOP", "GATHERS", "GATHER", "SRUNS", "SRUN", "REST", "END"]
def var(n, out):
    while True:
        b = n & 127; n >>= 7
        if n: out.append(b | 128)
        else: out.append(b); return
# INT5: string gaps (backslash, newline, two spaces) every 128 hex digits: same value, and no identifier-character run
# longer than 128 (the core's source rule's RAW regex is quadratic in such a run: ~8 min per 512 KiB line).
def gap(h, w=128):
    return "\\\n  ".join(h[i:i + w] for i in range(0, len(h), w))
def main(cls, outdir, chunk=512 * 1024):
    lines = [l.split() for l in open(cls).read().split("\n") if l.strip()]
    dct, dix = [], {}
    for l in lines:
        for t in l:
            if t not in KW:
                v = int(t)
                if v >= 2 ** 32 and v not in dix: dix[v] = len(dct); dct.append(v)
    out = bytearray(); var(0x5048, out); var(1, out); var(len(dct), out)
    for v in dct: out += v.to_bytes(8, "little")
    var(len(lines), out)
    for l in lines:
        var(len(l), out)
        for t in l:
            if t in KW: var(4 * KW.index(t) + 1, out)
            else:
                v = int(t)
                var(4 * dix[v] + 2 if v >= 2 ** 32 else 4 * v, out)
    hx = out.hex(); cb = chunk
    n = max(1, (len(hx) + cb - 1) // cb)
    for k in range(n):
        open(os.path.join(outdir, f"Lvm6DataPhi{k}.lean"), "w").write(
            "-- Generated by phb.py (ST-4): the class table, PHB 1, lowercase hex. Do not edit.\n\nnamespace Lvm6.Data\n\n"
            f"def phiHex{k} : String := \"{gap(hx[k * cb:(k + 1) * cb])}\"\n\nend Lvm6.Data\n")
    imps = "".join(f"import Lvm6DataPhi{k}\n" for k in range(n))
    body = " ++ ".join(f"phiHex{k}" for k in range(n))
    open(os.path.join(outdir, "Lvm6DataPhi.lean"), "w").write(
        f"-- Generated by phb.py (ST-4). Do not edit.\n{imps}\nnamespace Lvm6.Data\n\ndef phiHex : String := {body}\n\nend Lvm6.Data\n")
    print(f"lines {len(lines)}, dictionary {len(dct)}, bytes {len(out)}, hex {len(hx)}, modules {n}")
if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
